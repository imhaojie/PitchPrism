"""Export the SAME UI with materialized Python facts for free GitHub Pages hosting.

No second analytics engine and no mock model call: the public static variant explicitly
uses local evidence mode. Facts/stories are generated by the production Python modules.
"""
import argparse
import itertools
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from product.football.analytics import local_story, snapshot
from product.football.server import MATCH


def export_demo(target):
    source = ROOT / 'product/football'
    shutil.copytree(source / 'watch', target, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('node_modules', 'package*.json', 'tests', '__pycache__'))
    for module in ['media', 'stage', 'adapters']:
        shutil.copytree(ROOT / 'product/watch' / module, target / 'shared' / module, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns('*.test.js'))
    for name in ['source.mp4', 'enhanced.mp4', 'manifest.json']:
        path = source / 'build' / name
        if not path.is_file():
            raise RuntimeError('Render the media before exporting; missing ' + name)
        (target / 'media').mkdir(exist_ok=True)
        shutil.copy2(path, target / 'media' / name)
    states = [snapshot(MATCH, second) for second in [0, *[e['second'] for e in MATCH['events']]]]
    stories = {}
    for index, state in enumerate(states):
        for mode, team, player in itertools.product(['casual', 'analyst'], ['all', 'NBR', 'RIV'], ['all', *[p['id'] for p in MATCH['roster']]]):
            stories[f'{index}|{mode}|{team}|{player}'] = local_story(state, mode, team, player)
    final = snapshot(MATCH, 48)
    data = {'match': MATCH, 'states': states, 'stories': stories,
            'recap': {'synthetic': True, 'scope': final['scope'], 'stats': final['stats'], 'story': local_story(final)}}
    (target / 'demo-data.json').write_text(json.dumps(data, separators=(',', ':')))
    (target / 'app.js').write_text((target / 'app.js').read_text().replace('const STATIC_DEMO=false;', 'const STATIC_DEMO=true;'))
    html = (target / 'index.html').read_text().replace('href="/', 'href="./').replace('src="/', 'src="./').replace('poster="/', 'poster="./')
    (target / 'index.html').write_text(html)
    (target / '.nojekyll').touch()
    print(f'Exported {len(states)} event states and {len(stories)} local viewing combinations to {target}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=ROOT / 'product/football/build/site')
    args = parser.parse_args()
    export_demo(args.out)
